/*.Write a program to take a character input and print its corresponding ASCII value using typecasting. */


#include<stdio.h>
void main()
{
    char A = 'j';
    char B = '@';
    char C = 'h';

    int d=A;
    int e=B;
    int f=C;




    printf("%d\n",d);
    printf("%d\n",e);
    printf("%d\n",f);
}
